// Helper: map an encyclopedia.db row to a standard API response
function encRowToApi(row) {
  if (!row) return null;
  const BASE_URL = process.env.API_BASE_URL || `http://localhost:${PORT}`;
  return {
    id:                row.speciesId,
    tsn:               row.itisRecordId,
    speciesId:         row.speciesId,
    itisRecordId:      row.itisRecordId,
    kingdom:           row.kingdom,
    phylum:            row.phylum,
    class_name:        row.class,
    order:             row.order_name,
    family:            row.family,
    genus:             row.genus,
    scientific_name:   row.scientificName,
    common_name:       row.commonName,
    conservationStatus: row.conservationStatus,
    conservation_status: row.conservationStatus,
    habitat:           row.habitat,
    diet:              row.diet,
    lifespan:          row.lifespan,
    description:       row.description,
    wikipediaUrl:      row.wikipediaUrl,
    wikimediaUrl:      row.wikimediaUrl,
    localImagePath:    row.localImagePath,
    imageVerified:     row.imageVerified === 1,
    // Serve the image via our local static endpoint, with fallback to wikimediaUrl if not local/verified
    image:             row.localImagePath && row.imageVerified
                         ? `${BASE_URL}/${row.localImagePath}`
                         : (row.wikimediaUrl || null),
    imageUrl:          row.localImagePath && row.imageVerified
                         ? `${BASE_URL}/${row.localImagePath}`
                         : (row.wikimediaUrl || null),
    image_gallery:     row.localImagePath && row.imageVerified
                         ? [`${BASE_URL}/${row.localImagePath}`]
                         : (row.wikimediaUrl ? [row.wikimediaUrl] : []),
    lastUpdated:       row.lastUpdated,
  };
}

app.get('/api/encyclopedia/search', async (req, res) => {
  const { query, q, class_name, page, limit } = req.query;
  const searchQuery = (query || q || '').trim();
  const pg          = Math.max(1, parseInt(page) || 1);
  const lim         = Math.min(200, Math.max(1, parseInt(limit) || 50));
  const offset      = (pg - 1) * lim;
  const cls         = (class_name || '').toLowerCase();

  const edb = getEncDb();
  if (edb) {
    // ── Use permanent encyclopedia.db ──
    try {
      let sql   = 'SELECT * FROM species WHERE 1=1';
      let cntSql = 'SELECT COUNT(*) AS total FROM species WHERE 1=1';
      const params = [];

      if (cls && cls !== 'all') {
        sql    += ' AND LOWER(class)=?';
        cntSql += ' AND LOWER(class)=?';
        params.push(cls);
      }
      if (searchQuery) {
        const like = `%${searchQuery}%`;
        sql    += ' AND (scientificName LIKE ? OR commonName LIKE ? OR family LIKE ? OR habitat LIKE ?)';
        cntSql += ' AND (scientificName LIKE ? OR commonName LIKE ? OR family LIKE ? OR habitat LIKE ?)';
        params.push(like, like, like, like);
      }
      sql += ' ORDER BY commonName LIMIT ? OFFSET ?';

      const total   = edb.prepare(cntSql).get(...params).total;
      const results = edb.prepare(sql).all(...params, lim, offset);

      return res.json({
        total, page: pg, limit: lim,
        dataset_source: 'EcoTrack Encyclopedia SQLite (Permanent Database)',
        results: results.map(encRowToApi),
      });
    } catch (err) {
      console.error('Encyclopedia DB query error:', err.message);
    }
  }

  // ── Fallback: encyclopedia.json dataset ──
  try {
    const encPath = path.join(__dirname, 'encyclopedia.json');
    if (fs.existsSync(encPath)) {
      const eData = JSON.parse(fs.readFileSync(encPath, 'utf8'));
      let list = (Array.isArray(eData) ? eData : (eData.results || [])).map(r => ({
        id:                 r.id || r.tsn,
        tsn:                r.tsn || r.id,
        speciesId:          r.id || r.tsn,
        scientific_name:    r.scientific_name || r.scientificName || r.latin,
        common_name:        r.common_name || r.commonName || r.name,
        class_name:         r.class_name || r.class || r.animalClass || 'Mammalia',
        conservationStatus: r.conservation_status || r.status || 'LC',
        habitat:            r.habitat || 'Wild Habitat',
        diet:               r.diet || 'Omnivore',
        lifespan:           r.lifespan || '8-15 years',
        description:        r.description || r.desc || `Verified species record.`,
        image:              r.image || r.imageUrl,
        imageUrl:           r.imageUrl || r.image,
        imageVerified:      true,
      }));

      if (cls && cls !== 'all') {
        list = list.filter(x => (x.class_name || '').toLowerCase() === cls);
      }
      if (searchQuery) {
        const lq = searchQuery.toLowerCase();
        list = list.filter(x => (x.common_name || '').toLowerCase().includes(lq) || (x.scientific_name || '').toLowerCase().includes(lq));
      }

      const total = list.length;
      const results = list.slice(offset, offset + lim);

      return res.json({
        total, page: pg, limit: lim,
        dataset_source: 'EcoTrack Encyclopedia JSON Dataset',
        results,
      });
    }
  } catch (err) {
    console.error('Encyclopedia JSON fallback error:', err.message);
  }

  // Final fallback
  const result = db.searchEncyclopedia(searchQuery, class_name || 'All', pg, lim);
  res.json({ ...result, dataset_source: 'EcoTrack Legacy In-Memory' });
});

