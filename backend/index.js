app.post('/api/auth/verify-otp', (req, res) => {
  const { email, otp } = req.body;
  if (!email || !otp) return res.status(400).json({ error: "Email and OTP code are required." });

  const record = activeOtps.get(email.trim().toLowerCase());
  if (!record) {
    return res.status(400).json({ error: "No OTP request found for this email. Please request a new code." });
  }

  if (Date.now() > record.expiresAt) {
    activeOtps.delete(email.trim().toLowerCase());
    return res.status(400).json({ error: "OTP has expired after 5 minutes. Please request a new code." });
  }

  if (record.otp !== otp.trim()) {
    return res.status(400).json({ error: "Invalid OTP code. Please check the code sent to your email." });
  }

  record.verified = true;
  res.json({ message: "OTP verified successfully.", valid: true });
});

app.post('/api/auth/reset-password', (req, res) => {
  const { email, otp, newPassword } = req.body;
  if (!email || !otp || !newPassword) return res.status(400).json({ error: "Email, OTP, and new password are required." });
  if (newPassword.length < 6) return res.status(400).json({ error: "Password must be at least 6 characters." });

  const record = activeOtps.get(email.trim().toLowerCase());
  if (!record || !record.verified || record.otp !== otp.trim()) {
    return res.status(400).json({ error: "Invalid or expired session. Please verify your OTP code first." });
  }

  if (Date.now() > record.expiresAt) {
    activeOtps.delete(email.trim().toLowerCase());
    return res.status(400).json({ error: "Session expired after 5 minutes. Please request a new OTP." });
  }

  const resetRes = db.resetUserPassword(email.trim(), newPassword);
  if (resetRes.error) return res.status(400).json({ error: resetRes.error });

  activeOtps.delete(email.trim().toLowerCase());
  res.json({ message: "Password updated successfully! You can now log in with your new password." });
});

