const { getSocialDB } = require('./social_sqlite');

const parseOptionalAuth = async (req) => {
  const authHeader = req.headers.authorization;
  if (authHeader && authHeader.startsWith('Bearer ')) {
    const token = authHeader.split(' ')[1];
    if (token && token.startsWith('ecotrack_')) {
      try {
        const encoded = token.slice('ecotrack_'.length);
        const decoded = Buffer.from(encoded, 'base64').toString('utf8');
        const [userId, email] = decoded.split(':');
        if (userId && email) {
          const cleanId = cleanUserId(userId);
          const cleanEmail = email.toLowerCase().trim();
          const sdb = getSocialDB();
          let user = await sdb.prepare(`
            SELECT * FROM Users 
            WHERE (id = ? OR id = ? OR ecotrack_id = ?) AND LOWER(email) = ?
          `).get(userId, 'usr_' + cleanId, userId, cleanEmail);
          if (!user) {
            user = await sdb.prepare(`SELECT * FROM Users WHERE LOWER(email) = ?`).get(cleanEmail);
          }
          if (user) req.user = user;
        }
      } catch (err) {}
    }
  }
};

const requireAuth = async (req, res, next) => {
  const authHeader = req.headers.authorization;
  if (!authHeader || !authHeader.startsWith('Bearer ')) {
    return res.status(401).json({ error: 'Unauthorized: No token provided' });
  }
  const token = authHeader.split(' ')[1];
  if (!token || !token.startsWith('ecotrack_')) {
    return res.status(401).json({ error: 'Unauthorized: Invalid token format' });
  }
  try {
    const encoded = token.slice('ecotrack_'.length);
    const decoded = Buffer.from(encoded, 'base64').toString('utf8');
    const [userId, email] = decoded.split(':');
    if (!userId || !email) {
      return res.status(401).json({ error: 'Unauthorized: Malformed token payload' });
    }
    const cleanId = cleanUserId(userId);
    const cleanEmail = email.toLowerCase().trim();
    const sdb = getSocialDB();
    let user = await sdb.prepare(`
      SELECT * FROM Users 
      WHERE (id = ? OR id = ? OR ecotrack_id = ?) AND LOWER(email) = ?
    `).get(userId, 'usr_' + cleanId, userId, cleanEmail);

    if (!user) {
      user = await sdb.prepare(`SELECT * FROM Users WHERE LOWER(email) = ?`).get(cleanEmail);
    }

    if (!user) {
      return res.status(401).json({ error: 'Unauthorized: User session expired or invalid' });
    }
    req.user = user;
    next();
  } catch (err) {
    console.error('[requireAuth Error]:', err);
    return res.status(401).json({ error: 'Unauthorized: Invalid token signature' });
  }
};

function cleanUserId(id) {
  if (!id) return id;
  return String(id).replace(/^(user_|seller_|usr_|usr)/, '');
}

async function getRealUserId(ident) {
  if (!ident) return ident;
  try {
    const socialDb = getSocialDB();
    const cleanIdent = cleanUserId(ident);
    const u = await socialDb.prepare(`
      SELECT id FROM Users 
      WHERE id = ? OR ecotrack_id = ? OR id = ? OR ecotrack_id = ? OR id = ? OR ecotrack_id = ?
    `).get(ident, ident, 'usr_' + ident, 'usr_' + ident, cleanIdent, cleanIdent);
    if (u) return u.id;
  } catch (err) {
    console.warn("Error in getRealUserId:", err.message);
  }
  const clean = cleanUserId(ident);
  return clean ? 'usr_' + clean : ident;
}

function isAuthorizedUser(req, targetId) {
  if (!req.user || !targetId) return false;
  const cleanTarget = cleanUserId(targetId);
  const cleanUser = cleanUserId(req.user.id);
  const cleanEco = cleanUserId(req.user.ecotrack_id);
  return cleanUser === cleanTarget || cleanEco === cleanTarget || req.user.id === targetId || req.user.ecotrack_id === targetId;
}


