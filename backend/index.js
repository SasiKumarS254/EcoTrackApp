// Loads the permanent encyclopedia.db generated by the pipeline script
const ENC_DB_PATH = path.join(__dirname, 'encyclopedia.db');
let encDb = null;
function getEncDb() {
  if (encDb) return encDb;
  if (!fs.existsSync(ENC_DB_PATH)) return null;
  try {
    let Database;
    try { Database = require('better-sqlite3'); }
    catch { Database = require(path.join(__dirname, 'node_modules', 'better-sqlite3')); }
    encDb = new Database(ENC_DB_PATH, { readonly: true });
    encDb.pragma('journal_mode = WAL');
    console.log('📚 encyclopedia.db loaded successfully');
    return encDb;
  } catch (err) {
    console.warn('⚠️  encyclopedia.db not available:', err.message);
    return null;
  }
}
