/**
 * POST /api/ai/training-pipeline
 * Validate a training dataset submission.
 * Returns counts of valid, invalid, and duplicate samples.
 */
app.post('/api/ai/training-pipeline', async (req, res) => {
  const { samples } = req.body;
  if (!Array.isArray(samples)) {
    return res.status(400).json({ error: 'samples array required' });
  }

  const seen = new Set();
  let valid = 0, invalid = 0, duplicates = 0;
  const issues = [];

  for (let i = 0; i < samples.length; i++) {
    const s = samples[i];
    // Check required fields
    if (!s.image_id || !s.species || !s.keypoints) {
      invalid++;
      issues.push({ index: i, reason: 'Missing required fields: image_id, species, keypoints' });
      continue;
    }
    // Check keypoint count
    if (!Array.isArray(s.keypoints) || s.keypoints.length < 4) {
      invalid++;
      issues.push({ index: i, reason: `Insufficient keypoints: ${s.keypoints?.length ?? 0} (minimum 4)` });
      continue;
    }
    // Check for duplicates by image_id
    if (seen.has(s.image_id)) {
      duplicates++;
      issues.push({ index: i, reason: `Duplicate image_id: ${s.image_id}` });
      continue;
    }
    seen.add(s.image_id);
    valid++;
  }

  res.json({
    total: samples.length,
    valid,
    invalid,
    duplicates,
    qualityScore: Math.round((valid / Math.max(1, samples.length)) * 100),
    issues: issues.slice(0, 20),  // Cap at 20 issues for readability
    recommendation: valid >= samples.length * 0.9
      ? 'Dataset quality is sufficient for training.'
      : `Dataset has significant issues. Fix ${invalid + duplicates} samples before training.`,
  });
});



