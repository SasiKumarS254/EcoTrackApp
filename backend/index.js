// POST /api/social/follow/manage (Accept, Reject, Remove, Block)
app.post('/api/social/follow/manage', async (req, res) => {
  try {
    const socialDb = getSocialDB();
    const { action, target_id } = req.body;
    const actor_id = req.user.id; // Always enforce token identity as actor
    if (!action || !target_id) return res.status(400).json({ error: 'action and target_id required' });

    if (action === 'accept') {
      await socialDb.prepare(`UPDATE Followers SET status = 'Approved' WHERE follower_id = ? AND following_id = ?`).run(target_id, actor_id);
      return res.json({ message: 'Follow request accepted' });
    } else if (action === 'reject' || action === 'cancel') {
      await socialDb.prepare(`DELETE FROM Followers WHERE follower_id = ? AND following_id = ?`).run(target_id, actor_id);
      return res.json({ message: 'Follow request removed' });
    } else if (action === 'remove_follower') {
      await socialDb.prepare(`DELETE FROM Followers WHERE follower_id = ? AND following_id = ?`).run(target_id, actor_id);
      return res.json({ message: 'Follower removed' });
    } else if (action === 'block') {
      await socialDb.prepare(`DELETE FROM Followers WHERE (follower_id = ? AND following_id = ?) OR (follower_id = ? AND following_id = ?)`).run(actor_id, target_id, target_id, actor_id);
      await socialDb.prepare(`INSERT OR IGNORE INTO BlockedUsers (blocker_id, blocked_id) VALUES (?, ?)`).run(actor_id, target_id);
      return res.json({ message: 'User blocked' });
    }

    res.status(400).json({ error: 'Invalid management action' });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

