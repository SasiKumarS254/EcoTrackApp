// DELETE /api/social/messages/:id (Delete for me / delete for all)
app.delete('/api/social/messages/:id', async (req, res) => {
  try {
    if (!req.user) await parseOptionalAuth(req);
    const rawUserId = req.user ? req.user.id : (req.headers['x-user-id'] || req.query.user_id || 'usr1');
    if (!rawUserId) {
      return res.status(401).json({ error: 'Unauthorized: User identification required' });
    }
    const socialDb = getSocialDB();
    const messageId = parseInt(req.params.id, 10);
    const userId = await getRealUserId(rawUserId);
    const { delete_type } = req.query; // 'me' or 'all'
    
    const msg = await socialDb.prepare(`SELECT * FROM Messages WHERE id = ?`).get(messageId);
    if (!msg) {
      return res.status(404).json({ error: "Message not found" });
    }
    
    const msgSenderId = await getRealUserId(msg.sender_id);
    const msgReceiverId = await getRealUserId(msg.receiver_id);

    const isSender = String(msgSenderId) === String(userId) || cleanUserId(msgSenderId) === cleanUserId(userId);
    const isReceiver = String(msgReceiverId) === String(userId) || cleanUserId(msgReceiverId) === cleanUserId(userId);
    
    if (!isSender && !isReceiver) {
      return res.status(403).json({ error: "Forbidden: You are not a participant in this conversation" });
    }
    
    if (delete_type === 'all') {
      if (!isSender) {
        return res.status(403).json({ error: "Forbidden: Only the sender can delete a message for everyone" });
      }
      await socialDb.prepare(`UPDATE Messages SET is_deleted = 3 WHERE id = ?`).run(messageId);
    } else {
      let newDeletedState = msg.is_deleted;
      if (isSender) {
        newDeletedState = (msg.is_deleted === 2) ? 3 : 1;
      } else {
        newDeletedState = (msg.is_deleted === 1) ? 3 : 2;
      }
      await socialDb.prepare(`UPDATE Messages SET is_deleted = ? WHERE id = ?`).run(newDeletedState, messageId);
    }
    
    res.json({ success: true, message: "Message deleted successfully" });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

